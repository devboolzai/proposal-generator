// Word export all render it the same way — a new service is a new
// entry here and nothing else:
//
//   label        chip text in Step 2
//   icon         card icon in Step 2
//   title        section title in the document
//   description  optional paragraph under the title
//   fields       optional quick-fill inputs; each `{key}` placeholder in
//                an item is replaced with the field's value (or default)
//   platforms    optional platform picker; the title is then built from
//                the chosen platforms (socialTitle in state/sections.js)
//   groups       sub-lists: { heading, items, platforms? } — a group with
//                `platforms` only shows when one of them is picked
//
// Templates are only the starting point: once picked, the section is
// copied into the proposal and every line of it can be edited there.
// ============================================================

